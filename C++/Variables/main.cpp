#include <iostream>


int main(){

    // the general format for declaring variables is like so
    // data_type variable_name;

    // Like
    int a;
    bool b;
    char c;
    float f;
    double d;

    // you can even declare multiple variables in a single like like so
    int var1, var2, var3;

    // you can instantiate variables upon declaration like so
    char* name = "Skullfire-GT04";
    int age = 19;

    // you can do type conversion like so
    // variable = (data_type) value;

    // Like casting an int to a float like so:
    float f_age = (float) age;

    return 0;
}